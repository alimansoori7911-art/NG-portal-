import api from './api'

const unwrap = (res) => res.data?.data

/**
 * گزارش‌های تجمیعی — ماژول `/admin/reports/*`.
 *
 * ✅ اسپک ۲۱ این را اضافه کرد. تا پیش از آن، کارت‌های بخش مالی فقط
 * جمعِ **یک صفحه** را نشان می‌دادند چون مسیر پرداخت‌ها صفحه‌بندی‌شده
 * است و جمع واقعی سیستم را نمی‌داد.
 */
export const reportService = {
    /**
     * GET /admin/reports/sales — جمع پرداخت‌ها در یک بازه.
     *
     * ⚠️ این یک **تجمیع** است نه فهرست صفحه‌بندی‌شده؛ خروجی فقط چهار
     * عدد دارد.
     *
     * ⚠️ `from` و `to` هر دو **الزامی**‌اند و بازه **شامل هر دو سر**
     * است. اسپک صریح می‌گوید تاریخ شمسی (`1404/06/01`) هم می‌پذیرد،
     * پس لازم نیست ورودی کاربر را به میلادی تبدیل کنیم.
     */
    getSales({ from, to }) {
        return api
            .get('/admin/reports/sales', { params: { from, to } })
            .then(unwrap)
    },
}
